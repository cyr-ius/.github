#!/usr/bin/env bash
# Sync the Python library CI templates into local repositories.
#
# Usage: py/sync.sh [--prune] <repo> [<repo>...]
#
#   --prune  remove the legacy workflow files replaced by the templates
#
# Workflows and dependabot.yml are always (re)written. Tests run on the
# minimum Python of `requires-python` and on the latest supported one.
set -euo pipefail

TEMPLATES="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/templates"
LATEST_PYTHON=3.14

# Workflow files from the previous per-repository CI, replaced by the templates.
LEGACY_WORKFLOWS=(
  auto-approve.yml
  python-lint.yml
  pythonpackage.yml
  pythonpublish.yml
  release.yml
  stale.yaml
)

usage() {
  sed -n '2,9s/^# \{0,1\}//p' "$0"
  exit "${1:-0}"
}

prune=false
repos=()
for arg in "$@"; do
  case $arg in
    --prune) prune=true ;;
    -h | --help) usage ;;
    -*) echo "unknown option: $arg" >&2; usage 1 ;;
    *) repos+=("$arg") ;;
  esac
done
((${#repos[@]})) || usage 1

render() {
  local src=$1 dest=$2
  mkdir -p "$(dirname "$dest")"
  sed -e "s/{{BRANCH}}/$BRANCH/g" -e "s/{{PYTHONS}}/$PYTHONS/g" "$src" >"$dest"
}

# JSON list of the minimum Python from requires-python and LATEST_PYTHON.
python_versions() {
  python3 - "$1/pyproject.toml" "$LATEST_PYTHON" <<'EOF'
import json, re, sys, tomllib

spec = tomllib.load(open(sys.argv[1], "rb")).get("project", {}).get("requires-python", "")
latest = sys.argv[2]
match = re.search(r">=\s*(\d+)\.(\d+)", spec)
versions = [f"{match[1]}.{match[2]}"] if match else []
if latest not in versions:
    versions.append(latest)
print(json.dumps(versions, separators=(",", ":")))
EOF
}

write_dependabot() {
  local repo=$1 eco
  local ecosystems=(github-actions)
  if [[ -f $repo/uv.lock ]]; then ecosystems+=(uv); else ecosystems+=(pip); fi
  if [[ -f $repo/.pre-commit-config.yaml ]]; then ecosystems+=(pre-commit); fi

  {
    printf -- '---\n# Generated by cyr-ius/.github py/sync.sh\n'
    printf 'version: 2\nupdates:\n'
    for eco in "${ecosystems[@]}"; do
      printf '  - package-ecosystem: "%s"\n    directory: "/"\n    schedule:\n      interval: "weekly"\n' "$eco"
    done
  } >"$repo/.github/dependabot.yml"
}

sync_repo() {
  local repo=${1%/} f
  if [[ ! -f $repo/pyproject.toml ]]; then
    echo "skip $repo: no pyproject.toml" >&2
    return
  fi
  BRANCH=$(git -C "$repo" symbolic-ref --quiet --short refs/remotes/origin/HEAD 2>/dev/null || echo origin/main)
  BRANCH=${BRANCH#origin/}
  PYTHONS=$(python_versions "$repo")

  local gh=$repo/.github
  mkdir -p "$gh/workflows"

  if $prune; then
    for f in "${LEGACY_WORKFLOWS[@]}"; do
      rm -f -- "$gh/workflows/$f"
    done
  fi

  for f in "$TEMPLATES"/workflows/*.yml; do
    if [[ $(basename "$f") == tests.yml && ! -d $repo/tests ]]; then continue; fi
    render "$f" "$gh/workflows/$(basename "$f")"
  done

  write_dependabot "$repo"

  echo "synced $repo (branch: $BRANCH, python: $PYTHONS)"
}

for repo in "${repos[@]}"; do
  sync_repo "$repo"
done
