#!/usr/bin/env bash
# Sync the Python library CI templates into local repositories.
#
# Usage: py/sync.sh [--prune] [--commit|--pr|--merge] [--message=TEXT] <repo> [<repo>...]
#
#   --prune          remove the legacy workflow files replaced by the templates
#   --commit         sync into a clean worktree of the remote base branch and
#                    commit there, on branch ci/sync-templates-<sha>
#   --pr             also push the branch (SSH) and open a pull request
#   --merge          also enable auto-merge (squash) on the pull request
#   --message=TEXT   commit / pull request title
#
# With --commit, --pr or --merge the repository's checkout is left untouched
# (see lib/publish.sh).
#
# Workflows and dependabot.yml are always (re)written. Tests run on the
# Python versions set by default in py-tests.yml.
set -euo pipefail

TEMPLATES="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/templates"
source "$(dirname "${BASH_SOURCE[0]}")/../lib/publish.sh"

# Workflow files from the previous per-repository CI, replaced by the templates.
LEGACY_WORKFLOWS=(
  auto-approve.yml
  python-lint.yml
  pythonpackage.yml
  pythonpublish.yml
  release.yml
  stale.yaml
)

usage() {
  sed -n '2,17s/^# \{0,1\}//p' "$0"
  exit "${1:-0}"
}

prune=false
repos=()
for arg in "$@"; do
  case $arg in
    --prune) prune=true ;;
    -h | --help) usage ;;
    --commit | --pr | --merge | --message=*) publish_option "$arg" ;;
    -*) echo "unknown option: $arg" >&2; usage 1 ;;
    *) repos+=("$arg") ;;
  esac
done
((${#repos[@]})) || usage 1
PUBLISH_ARGS=(py/sync.sh)
$prune && PUBLISH_ARGS+=(--prune)

render() {
  local src=$1 dest=$2
  mkdir -p "$(dirname "$dest")"
  sed -e "s/{{BRANCH}}/$BRANCH/g" "$src" >"$dest"
}


write_dependabot() {
  local repo=$1 eco prefix
  local ecosystems=(github-actions)
  if [[ -f $repo/uv.lock ]]; then ecosystems+=(uv); else ecosystems+=(pip); fi
  if [[ -f $repo/.pre-commit-config.yaml ]]; then ecosystems+=(pre-commit); fi

  {
    printf -- '---\n# Generated by cyr-ius/.github py/sync.sh\n'
    printf 'version: 2\nupdates:\n'
    for eco in "${ecosystems[@]}"; do
      # Conventional Commits: "ci(deps): ..." for actions, "chore(deps): ..." otherwise
      if [[ $eco == github-actions ]]; then prefix=ci; else prefix=chore; fi
      printf '  - package-ecosystem: "%s"\n    directory: "/"\n    schedule:\n      interval: "weekly"\n' "$eco"
      printf '    commit-message:\n      prefix: "%s"\n      include: "scope"\n' "$prefix"
    done
  } >"$repo/.github/dependabot.yml"
}

sync_repo() {
  local repo=${1%/} f
  if [[ ! -f $repo/pyproject.toml ]]; then
    echo "skip $repo: no pyproject.toml" >&2
    return
  fi
  BRANCH=$(git -C "$repo" symbolic-ref --quiet --short refs/remotes/origin/HEAD 2>/dev/null || echo origin/main)
  BRANCH=${BRANCH#origin/}

  local gh=$repo/.github
  mkdir -p "$gh/workflows"

  if $prune; then
    for f in "${LEGACY_WORKFLOWS[@]}"; do
      rm -f -- "$gh/workflows/$f"
    done
  fi

  for f in "$TEMPLATES"/workflows/*.yml; do
    if [[ $(basename "$f") == tests.yml && ! -d $repo/tests ]]; then continue; fi
    render "$f" "$gh/workflows/$(basename "$f")"
  done

  write_dependabot "$repo"

  echo "synced $repo (branch: $BRANCH)"
}

sync_all "${repos[@]}"
