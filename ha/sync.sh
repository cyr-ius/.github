#!/usr/bin/env bash
# Sync the Home Assistant CI templates into local integration repositories.
#
# Usage: ha/sync.sh [--prune] [--force] <repo> [<repo>...]
#
#   --prune  remove the legacy workflow files replaced by the templates
#   --force  overwrite the repository's own issue / pull request templates
#
# Workflows and dependabot.yml are always (re)written. Issue and pull request
# templates are only written when the repository has none, unless --force.
set -euo pipefail

TEMPLATES="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/templates"

# Workflow files from the previous per-repository CI, replaced by the templates.
LEGACY_WORKFLOWS=(
  auto-approve.yml
  check-lint.yml
  hacs.yml
  hassfest.yaml
  lint.yml
  pytest.yml
  release.yaml
  stale.yaml
  validate-for-hacs.yml
  validate-with-hassfest.yml
)

usage() {
  sed -n '2,10s/^# \{0,1\}//p' "$0"
  exit "${1:-0}"
}

prune=false
force=false
repos=()
for arg in "$@"; do
  case $arg in
    --prune) prune=true ;;
    --force) force=true ;;
    -h | --help) usage ;;
    -*) echo "unknown option: $arg" >&2; usage 1 ;;
    *) repos+=("$arg") ;;
  esac
done
((${#repos[@]})) || usage 1

# Escape a string for use as a sed replacement.
sed_escape() {
  printf '%s' "$1" | sed 's/[&/\]/\\&/g'
}

render() {
  local src=$1 dest=$2
  mkdir -p "$(dirname "$dest")"
  sed -e "s/{{NAME}}/$NAME/g" -e "s/{{DOMAIN}}/$DOMAIN/g" -e "s/{{BRANCH}}/$BRANCH/g" "$src" >"$dest"
}

write_dependabot() {
  local repo=$1 eco
  local ecosystems=(github-actions)
  if [[ -f $repo/uv.lock ]]; then ecosystems+=(uv); fi
  if [[ -f $repo/.pre-commit-config.yaml ]]; then ecosystems+=(pre-commit); fi
  if [[ -d $repo/.devcontainer ]]; then ecosystems+=(devcontainers); fi

  {
    printf -- '---\n# Generated by cyr-ius/.github ha/sync.sh\n'
    printf 'version: 2\nupdates:\n'
    for eco in "${ecosystems[@]}"; do
      printf '  - package-ecosystem: "%s"\n    directory: "/"\n    schedule:\n      interval: "weekly"\n' "$eco"
    done
  } >"$repo/.github/dependabot.yml"
}

sync_repo() {
  local repo=${1%/} f
  local manifests=("$repo"/custom_components/*/manifest.json)
  if ((${#manifests[@]} != 1)) || [[ ! -f ${manifests[0]} ]]; then
    echo "skip $repo: expected exactly one custom_components/<domain>/manifest.json" >&2
    return
  fi
  DOMAIN=$(sed_escape "$(basename "$(dirname "${manifests[0]}")")")
  NAME=$(sed_escape "$(jq -r '.name' "${manifests[0]}")")
  BRANCH=$(git -C "$repo" symbolic-ref --quiet --short refs/remotes/origin/HEAD 2>/dev/null || echo origin/main)
  BRANCH=$(sed_escape "${BRANCH#origin/}")

  local gh=$repo/.github
  mkdir -p "$gh/workflows"

  if $prune; then
    for f in "${LEGACY_WORKFLOWS[@]}"; do
      rm -f -- "$gh/workflows/$f"
    done
  fi

  for f in "$TEMPLATES"/workflows/*.yml; do
    if [[ $(basename "$f") == tests.yml && ! -d $repo/tests ]]; then continue; fi
    render "$f" "$gh/workflows/$(basename "$f")"
  done

  write_dependabot "$repo"

  if $force || [[ ! -d $gh/ISSUE_TEMPLATE ]]; then
    rm -rf -- "$gh/ISSUE_TEMPLATE"
    for f in "$TEMPLATES"/ISSUE_TEMPLATE/*; do
      render "$f" "$gh/ISSUE_TEMPLATE/$(basename "$f")"
    done
  fi
  if $force || [[ ! -f $gh/PULL_REQUEST_TEMPLATE.md ]]; then
    render "$TEMPLATES/PULL_REQUEST_TEMPLATE.md" "$gh/PULL_REQUEST_TEMPLATE.md"
  fi

  echo "synced $repo (domain: $DOMAIN, branch: $BRANCH)"
}

for repo in "${repos[@]}"; do
  sync_repo "$repo"
done
